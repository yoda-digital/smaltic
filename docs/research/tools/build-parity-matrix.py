"""Collect every REQ-* requirement from rea/*.md into parity-matrix.md (ID, priority, requirement, source, status).

Usage: python3 -I docs/research/tools/build-parity-matrix.py [--status-from <dir>]

--status-from <dir> reads <dir>/report.json, the output of `vitest run --reporter=json --outputFile=report.json`
(tests/compat: `pnpm --filter compat test:report`). In test names a bare id (`REQ-API-007`) claims full
coverage and `REQ-API-007~` partial coverage. A bare id in a passing test gives `done (<test file>)`; an id
only `~`-tagged in passing tests gives `partial (<test file>)`. An id named (bare or `~`) by a failing test
stays `todo`; todo and skipped tests change nothing.
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
repo_root = root.parent.parent
pat_list = re.compile(r'^\s*-\s+\*{0,2}(REQ-[A-Z0-9]+-\d+)\s*\((P[0-2])\)\*{0,2}\s*(.*)$')
pat_table = re.compile(r'^\|\s*(REQ-[A-Z0-9]+-\d+)\s*\|\s*(P[0-2])\s*\|\s*(.*?)\s*\|')
pat_id = re.compile(r'(REQ-[A-Z0-9]+-\d+)(~?)')


def parse_args(argv):
    status_dir = None
    i = 0
    while i < len(argv):
        if argv[i] == '--status-from' and i + 1 < len(argv):
            status_dir = pathlib.Path(argv[i + 1]); i += 2
        elif argv[i].startswith('--status-from='):
            status_dir = pathlib.Path(argv[i].split('=', 1)[1]); i += 1
        else:
            sys.exit(f'usage: build-parity-matrix.py [--status-from <dir>] (unknown argument {argv[i]!r})')
    return status_dir


def test_file_label(name):
    p = pathlib.Path(name)
    try:
        return p.resolve().relative_to(repo_root).as_posix()
    except ValueError:
        return p.name


def statuses_from(report_path):
    """(done, partial): REQ id -> sorted test files. Ids named by a failing test are in neither."""
    report = json.loads(report_path.read_text())
    full, part, failed = {}, {}, set()
    for suite in report.get('testResults', []):
        label = test_file_label(suite.get('name', '?'))
        for t in suite.get('assertionResults', []):
            tags = set(pat_id.findall(' '.join(t.get('ancestorTitles', []) + [t.get('title', '')])))
            if t.get('status') == 'passed':
                for rid, partial in tags:
                    (part if partial else full).setdefault(rid, set()).add(label)
            elif t.get('status') == 'failed':
                failed |= {rid for rid, _ in tags}
    done = {rid: sorted(files) for rid, files in full.items() if rid not in failed}
    partial = {rid: sorted(files) for rid, files in part.items() if rid not in failed and rid not in done}
    return done, partial


status_dir = parse_args(sys.argv[1:])
done, partial = {}, {}
if status_dir is not None:
    report_path = status_dir / 'report.json'
    if not report_path.is_file():
        sys.exit(f'{report_path} not found: run `pnpm --filter compat test:report` first')
    done, partial = statuses_from(report_path)

reqs = {}
for f in sorted((root / 'rea').glob('0*.md')):
    lines = f.read_text().splitlines()
    for i, line in enumerate(lines):
        m = pat_list.match(line) or pat_table.match(line)
        if not m:
            continue
        rid, prio, text = m.groups()
        j = i + 1  # list items may wrap onto indented continuation lines
        while pat_list is not None and j < len(lines) and lines[j].startswith('  ') and not pat_list.match(lines[j]):
            text += ' ' + lines[j].strip(); j += 1
        text = re.sub(r'\s+', ' ', text).replace('|', '\\|')
        reqs.setdefault(rid, (prio, text, f'rea/{f.name}:{i+1}'))
order = lambda r: (r.split('-')[1], int(r.split('-')[2]))
out = ['# Parity matrix (generated by tools/build-parity-matrix.py — do not edit by hand)', '',
       'Status column is updated by the build plan: `todo` → `done` (with test reference) or `wontdo` (with reason).',
       '`done` / `partial` come from passing compat tests (`tests/compat`, `--status-from tests/compat`): a bare REQ id in a test name claims full coverage, `REQ-…~` partial coverage.', '']
counts = {}
for rid in sorted(reqs, key=order):
    counts[reqs[rid][0]] = counts.get(reqs[rid][0], 0) + 1
n_done = sum(1 for rid in reqs if rid in done)
n_partial = sum(1 for rid in reqs if rid in partial)
out.append('Totals: ' + ', '.join(f'{k}: {v}' for k, v in sorted(counts.items()))
           + f', all: {len(reqs)}, done: {n_done}, partial: {n_partial}, todo: {len(reqs) - n_done - n_partial}')
out += ['', '| ID | Pri | Requirement | Source | Status |', '|---|---|---|---|---|']
for rid in sorted(reqs, key=order):
    p, t, s = reqs[rid]
    status = (f"done ({', '.join(done[rid])})" if rid in done
              else f"partial ({', '.join(partial[rid])})" if rid in partial else 'todo')
    out.append(f'| {rid} | {p} | {t} | {s} | {status} |')
unknown = sorted((set(done) | set(partial)) - set(reqs))
(root / 'parity-matrix.md').write_text('\n'.join(out) + '\n')
print(len(reqs), counts, f'done: {n_done}, partial: {n_partial}, todo: {len(reqs) - n_done - n_partial}')
if unknown:
    print('warning: test names mention unknown REQ ids:', ', '.join(unknown), file=sys.stderr)
