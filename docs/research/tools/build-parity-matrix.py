"""Collect every REQ-* requirement from rea/*.md into parity-matrix.md (ID, priority, requirement, source)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
pat_list = re.compile(r'^\s*-\s+\*{0,2}(REQ-[A-Z0-9]+-\d+)\s*\((P[0-2])\)\*{0,2}\s*(.*)$')
pat_table = re.compile(r'^\|\s*(REQ-[A-Z0-9]+-\d+)\s*\|\s*(P[0-2])\s*\|\s*(.*?)\s*\|')
reqs = {}
for f in sorted((root / 'rea').glob('0*.md')):
    lines = f.read_text().splitlines()
    for i, line in enumerate(lines):
        m = pat_list.match(line) or pat_table.match(line)
        if not m:
            continue
        rid, prio, text = m.groups()
        j = i + 1  # list items may wrap onto indented continuation lines
        while pat_list is not None and j < len(lines) and lines[j].startswith('  ') and not pat_list.match(lines[j]):
            text += ' ' + lines[j].strip(); j += 1
        text = re.sub(r'\s+', ' ', text).replace('|', '\\|')
        reqs.setdefault(rid, (prio, text, f'rea/{f.name}:{i+1}'))
order = lambda r: (r.split('-')[1], int(r.split('-')[2]))
out = ['# Parity matrix (generated by tools/build-parity-matrix.py — do not edit by hand)', '',
       'Status column is updated by the build plan: `todo` → `done` (with test reference) or `wontdo` (with reason).', '']
counts = {}
for rid in sorted(reqs, key=order):
    counts[reqs[rid][0]] = counts.get(reqs[rid][0], 0) + 1
out.append('Totals: ' + ', '.join(f'{k}: {v}' for k, v in sorted(counts.items())) + f', all: {len(reqs)}')
out += ['', '| ID | Pri | Requirement | Source | Status |', '|---|---|---|---|---|']
for rid in sorted(reqs, key=order):
    p, t, s = reqs[rid]
    out.append(f'| {rid} | {p} | {t} | {s} | todo |')
(root / 'parity-matrix.md').write_text('\n'.join(out) + '\n')
print(len(reqs), counts)
